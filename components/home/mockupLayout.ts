/**
 * 홈 화면 배치 — 좌표는 `design/호랑이잉글리시.png`(1179 × 3333) 실측값이다.
 *
 * ── 좌표계: x와 y의 기준이 다르다. 반드시 읽을 것 ──────────────────────
 *   x : 화면 왼쪽 끝 기준. 시안 x 그대로다.
 *   y : **안전영역(safe area) 아래끝 기준.** 시안 절대 y가 아니라 `시안 y − 222`다.
 *       각 항목 끝 주석에 원래 시안 y를 적어 뒀다 — 시안과 대조 검증할 때 쓴다.
 *
 * ── 왜 절대좌표인가 ────────────────────────────────────────────────────
 * 에셋을 시안에서 **1:1로 잘라냈고**(에셋마다 투명 여백도 없음), 아래 좌표는
 * 각 에셋을 시안 이미지에 대고 **템플릿 매칭**해 찾은 실측값이다(버튼 3종은
 * 오차 0.9~1.6/px = 사실상 정확).
 *
 * 세로 나열 + 간격(gap)으로 재현할 수 없다. **잔디가 호랑이 발을 덮기 때문**이다
 * (호랑이 209~1320, 잔디 1147~1766 → 173px 겹침). 간격 방식으로는 표현이 안 된다.
 * `%`나 `gap`을 어림잡다가 실제로 레이아웃이 무너졌다(2026-08-11).
 *
 * ── 왜 y만 안전영역 기준인가 (2026-08-15 확정) ─────────────────────────
 * 시안의 **상대 위치는 원본이지만 절대 세로 위치는 원본이 아니다.** 시안 맨 위
 * 222px는 딸이 상태바 자리로 비워둔 공간인데, 그 크기는 기기마다 다른 값을
 * 한 숫자로 추측한 것에 지나지 않는다. 그래서 그 구간을 걷어내고(전 좌표 −222),
 * 그 자리에 **OS가 기기별로 주는 `insets.top`을 끼워 넣는다.**
 *
 * 시안 절대좌표를 그대로 쓰면(= 캔버스를 화면 맨 위에 붙이면) 상태바가 위를 덮는
 * 만큼이 기기마다 달라서, 눈에 보이는 상단 여백이 **13.7pt(16 Pro) ~ 50.6pt(SE)**
 * 로 3.7배 벌어진다. 안전영역 기준에서는 전 기기가 `TOP_GAP_DESIGN_PX × s`로 같다.
 *
 * 원점을 태양(시안 y 222)으로 잡은 근거: 시안에서 가장 위에 있는 요소이고, 그 위는
 * 전부 빈 노트지다. 실측하면 딸이 그린 다이나믹 아일랜드는 시안 y 35~147로 실제
 * 아일랜드(11~48pt)와 거의 일치했다 — 위치를 틀리게 그린 게 아니라 그 아래 여백을
 * 넉넉히 잡았을 뿐이고, 그 여백을 안전영역이 대신하게 한 것이다.
 *
 * **태양보다 위에 새 요소를 두려면 y가 음수가 된다.** 그게 싫으면 전체 y를 다시
 * 베이스라인 잡아야 한다(전 항목에 같은 값을 더하는 기계적 작업 — 상대 위치는
 * 뺄셈으로 변하지 않으므로 레이아웃은 그대로다).
 *
 * ── 렌더 순서 주의 ────────────────────────────────────────────────────
 * **잔디를 호랑이보다 나중에** 그린다 — 시안에서 잔디가 호랑이 발을 덮는다.
 * (2026-08-14 정정. 그 전엔 반대로 알고 순서가 뒤바뀌어 있어 호랑이가 잔디 위에
 *  떠 있는 것처럼 보였다.)
 *
 * 잔디 이미지 위쪽은 풀잎 끝이라 거의 투명해서, 순서만 바꾸면 발이 풀 사이로 비치는
 * 시안 모습이 그대로 나온다 — 마스킹 같은 건 필요 없다.
 * 겹치는 구간에 든 호랑이 부분은 발과 말풍선 아래 끝 16px뿐이고,
 * `GrassGauge`가 `pointerEvents="none"`이라 터치는 그대로 통과한다.
 */

/**
 * 시안 이미지 폭(px). 배율의 분모이자 **시안 px과 화면 px을 잇는 유일한 지점**이다.
 *   const s = screenWidth / MOCKUP_WIDTH;
 */
export const MOCKUP_WIDTH = 1179;

/** 캔버스 높이(시안 px). 시안 높이 3333 − 걷어낸 상단 222. */
export const CANVAS_HEIGHT = 3111;

/**
 * 안전영역 아래끝과 첫 요소(태양) 사이 숨 쉴 틈(시안 px). `s`를 곱해 쓰므로 전 기기
 * 비율이 같다. **기기 추정치가 아니라 디자인 결정**이라는 점에서 걷어낸 222와 성격이
 * 다르다 — 0이면 태양 윗변이 안전영역 경계에 정확히 붙는다.
 *
 * 기본 0인 이유: 안전영역 경계 자체가 이미 다이나믹 아일랜드 아래끝보다 10pt 아래라
 * 0이어도 붙어 보이지 않는다. 실기기에서 빡빡하면 이 값만 올린다.
 */
export const TOP_GAP_DESIGN_PX = 0;

export interface Placement {
  x: number;
  y: number;
  w: number;
  h: number;
}

/** y는 안전영역 아래끝 기준(위 좌표계 항목 참조). 끝 주석은 대조용 원래 시안 y. */
export const PLACE = {
  sun: { x: 57, y: 0, w: 251, h: 227 }, // 시안 y 222
  tiger: { x: 58, y: 209, w: 1060, h: 1111 }, // 시안 y 431
  grass: { x: 130, y: 1147, w: 928, h: 619 }, // 시안 y 1369
  review: { x: 157, y: 1793, w: 866, h: 247 }, // 시안 y 2015
  pronunciation: { x: 133, y: 2042, w: 867, h: 248 }, // 시안 y 2264
  test: { x: 129, y: 2305, w: 875, h: 248 }, // 시안 y 2527
  flower: { x: 270, y: 2677, w: 135, h: 171 }, // 시안 y 2899
  ribbon: { x: 732, y: 2679, w: 176, h: 190 }, // 시안 y 2901
  mountains: { x: 0, y: 2970, w: 1179, h: 141 }, // 시안 y 3192
} as const satisfies Record<string, Placement>;

/** 배치 좌표 → 화면 스타일. `s`는 `screenWidth / MOCKUP_WIDTH`. */
export function place(p: Placement, s: number) {
  return {
    position: 'absolute' as const,
    left: p.x * s,
    top: p.y * s,
    width: p.w * s,
    height: p.h * s,
  };
}

/**
 * 캔버스 전체 높이(화면 px). 시안이 화면보다 길어 세로 스크롤된다(가이드 §7).
 * 산맥이 캔버스 바닥에 정확히 맞물린다: 2970 + 141 = 3111.
 */
export function canvasHeight(s: number) {
  return CANVAS_HEIGHT * s;
}
